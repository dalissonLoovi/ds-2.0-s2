/**
 * Illustration catalog codegen — reads tool/illustrations.json (written by
 * tool/extract_illustrations.mjs) and the cleaned SVGs under
 * assets/illustrations/, then writes:
 *
 *   Flutter  lib/src/generated/loovi_illustration_names.g.dart
 *   React    packages/react/src/illustrations/<group>/<name>.svg (copies)
 *            packages/react/src/illustrations/index.ts
 *
 * The Flutter assets are the canonical set (`<name>.flutter.svg`, when present,
 * is the flutter_svg-safe variant used by LooviIllustration only); React gets a byte-identical copy
 * under the catalog name (legacy Flutter paths such as
 * `assets/illustrations/vehicle/sedan.svg` map to `vehicle-icon/sedan.svg`).
 *
 * Usage (repo root): npm run flutter:illustrations
 *   = node packages/flutter_ds/tool/generate_illustrations.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(__dirname, '..');
const REACT_DIR = path.resolve(PKG, '../react/src/illustrations');
const OUT_DART = path.join(PKG, 'lib/src/generated/loovi_illustration_names.g.dart');

const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'illustrations.json'), 'utf8'));
const items = [...manifest.illustrations].sort((a, b) => a.name.localeCompare(b.name));

const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*\/[a-z0-9]+(-[a-z0-9]+)*$/;
const camel = (s) => s.replace(/[-/]([a-z0-9])/g, (_, c) => c.toUpperCase());
const fmt = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

const seen = new Set();
for (const it of items) {
  if (!NAME_RE.test(it.name)) throw new Error(`name outside kebab-case <group>/<name>: ${it.name}`);
  if (it.name.split('/')[0] !== it.group) throw new Error(`group mismatch: ${it.name}`);
  if (!fs.existsSync(path.join(PKG, it.asset))) throw new Error(`missing asset ${it.asset} — run extract_illustrations.mjs`);
  if (!(it.width > 0 && it.height > 0)) throw new Error(`missing size for ${it.name}`);
  const id = camel(it.name);
  if (seen.has(id)) throw new Error(`duplicate identifier ${id}`);
  seen.add(id);
}

// ---------------------------------------------------------------- Flutter
const dart = [
  '// GENERATED by packages/flutter_ds/tool/generate_illustrations.mjs — do not edit by hand.',
  '// Source: tool/illustrations.json (Figma mHm12Zu9tgNmaSYnooihE5, page 4326:1764).',
  '',
  '/// Artboard metadata of one DS illustration.',
  'final class LooviIllustrationSpec {',
  '  const LooviIllustrationSpec({',
  '    required this.name,',
  '    required this.asset,',
  '    required this.width,',
  '    required this.height,',
  '    required this.nodeId,',
  '  });',
  '',
  '  /// Catalog name `<group>/<name>`, e.g. `claim-reason/theft`.',
  '  final String name;',
  '',
  "  /// Asset path inside package `loovi_ds`.",
  '  final String asset;',
  '',
  '  /// Artboard size (SVG viewBox) in logical pixels.',
  '  final double width;',
  '  final double height;',
  '',
  '  /// Source COMPONENT node in Figma `[DS] 2.0 - S2`.',
  '  final String nodeId;',
  '',
  '  double get aspectRatio => width / height;',
  '}',
  '',
  '/// DS illustration names available in this package (`illustration / <group> / <name>`).',
  'abstract final class LooviIllustrations {',
  ...items.flatMap((it) => [
    `  /// \`${it.figmaName}\` — node ${it.nodeId}, ${it.width} × ${it.height}`,
    `  static const String ${camel(it.name)} = '${it.name}';`,
  ]),
  '',
  '  /// Every illustration, keyed by name.',
  '  static const Map<String, LooviIllustrationSpec> specs = {',
  ...items.map(
    (it) =>
      `    '${it.name}': LooviIllustrationSpec(name: '${it.name}', asset: '${it.flutterAsset ?? it.asset}', width: ${fmt(it.width)}, height: ${fmt(it.height)}, nodeId: '${it.nodeId}'),`,
  ),
  '  };',
  '',
  '  /// All names, sorted.',
  '  static List<String> get all => specs.keys.toList(growable: false);',
  '',
  '  /// Spec for [name], or null when it is not in the package.',
  '  static LooviIllustrationSpec? specOf(String name) => specs[name];',
  '}',
  '',
].join('\n');
fs.mkdirSync(path.dirname(OUT_DART), { recursive: true });
fs.writeFileSync(OUT_DART, dart);

// ---------------------------------------------------------------- React
fs.rmSync(REACT_DIR, { recursive: true, force: true });
for (const it of items) {
  const dest = path.join(REACT_DIR, `${it.name}.svg`);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(PKG, it.asset), dest);
}
const q = (s) => `'${s}'`;
const ts = [
  '// GENERATED by packages/flutter_ds/tool/generate_illustrations.mjs — do not edit by hand.',
  '// Source: packages/flutter_ds/tool/illustrations.json (Figma mHm12Zu9tgNmaSYnooihE5, page 4326:1764).',
  '',
  '/** Catalog name `<group>/<name>` of a DS illustration (`illustration / <group> / <name>` in Figma). */',
  'export type IllustrationName =',
  ...items.map((it, i) => `  | ${q(it.name)}${i === items.length - 1 ? ';' : ''}`),
  '',
  'export interface IllustrationMeta {',
  '  name: IllustrationName;',
  '  group: string;',
  '  /** Source COMPONENT node in Figma `[DS] 2.0 - S2`. */',
  '  nodeId: string;',
  '  /** Artboard size (SVG viewBox) in px. */',
  '  width: number;',
  '  height: number;',
  '}',
  '',
  'export const illustrations: Readonly<Record<IllustrationName, IllustrationMeta>> = {',
  ...items.map(
    (it) =>
      `  ${q(it.name)}: { name: ${q(it.name)}, group: ${q(it.group)}, nodeId: ${q(it.nodeId)}, width: ${it.width}, height: ${it.height} },`,
  ),
  '};',
  '',
  'export const illustrationNames = Object.keys(illustrations) as IllustrationName[];',
  '',
  '/**',
  ' * Lazy loaders: each SVG becomes its own chunk (`?raw` string), so consumers',
  ' * only download the artwork they render.',
  ' */',
  'export const illustrationLoaders: Readonly<Record<IllustrationName, () => Promise<{ default: string }>>> = {',
  ...items.map((it) => `  ${q(it.name)}: () => import('./${it.name}.svg?raw'),`),
  '};',
  '',
].join('\n');
fs.writeFileSync(path.join(REACT_DIR, 'index.ts'), ts);
fs.writeFileSync(
  path.join(REACT_DIR, 'svg-raw.d.ts'),
  "// GENERATED by packages/flutter_ds/tool/generate_illustrations.mjs — do not edit by hand.\ndeclare module '*.svg?raw' {\n  const source: string;\n  export default source;\n}\n",
);

console.log(`${items.length} illustrations → ${path.relative(PKG, OUT_DART)} + packages/react/src/illustrations/`);
